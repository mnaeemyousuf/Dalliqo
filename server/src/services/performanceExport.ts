import type { Writable } from 'node:stream';
import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';
import type { AgentPerformanceRow } from './performanceService';

const HEAD = ['Agent', 'Leads assigned', 'Contacted', 'Follow-ups done', 'Site visits', 'Negotiations', 'Deals closed', 'Commission (Rs)', 'Conversion %', 'Avg response (min)'];
const cells = (r: AgentPerformanceRow) => [r.fullName, r.leadsAssigned, r.leadsContacted, r.followUpsCompleted, r.siteVisits, r.negotiations, r.dealsClosed, r.commission, r.conversionPct ?? '', r.avgResponseMinutes ?? ''];

export async function agentPerformanceXlsx(rows: AgentPerformanceRow[], title: string, out: Writable) {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet('Agent performance');
  ws.addRow([title]).font = { bold: true, size: 13 };
  ws.addRow([]);
  const h = ws.addRow(HEAD);
  h.font = { bold: true };
  for (const r of rows) ws.addRow(cells(r));
  ws.columns.forEach((c, i) => (c.width = i === 0 ? 24 : 16));
  ws.getColumn(8).numFmt = '#,##0';
  await wb.xlsx.write(out);
  out.end();
}

export function agentPerformancePdf(rows: AgentPerformanceRow[], title: string, out: Writable): Promise<void> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 36 });
    doc.on('end', () => resolve());
    doc.on('error', reject);
    doc.pipe(out);
    doc.fontSize(14).text(title).moveDown(0.6);
    const widths = [140, 70, 60, 70, 60, 70, 60, 90, 70, 80];
    const row = (vals: (string | number)[], bold = false) => {
      const y = doc.y;
      let x = doc.page.margins.left;
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5);
      vals.forEach((v, i) => {
        doc.text(typeof v === 'number' ? v.toLocaleString('en-PK') : String(v), x, y, { width: widths[i] - 6, align: i ? 'right' : 'left' });
        x += widths[i];
      });
      doc.moveDown(0.6);
      if (doc.y > doc.page.height - 50) doc.addPage();
    };
    row(HEAD, true);
    for (const r of rows) row(cells(r));
    doc.moveDown(1).fontSize(7).fillColor('#64748b').text(`Generated by Stateown on ${new Date().toISOString().slice(0, 10)} from the records in the system.`);
    doc.end();
  });
}
