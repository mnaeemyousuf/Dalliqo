import { createHmac } from 'node:crypto';
import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { env } from '../../config/env';
import { safeEqual } from '../../utils/crypto';

export type ResourceType = 'image' | 'video' | 'raw';

export interface StoredObject {
  key: string;
  /** Stable public URL (gallery media). Private objects have no stored URL. */
  url?: string;
}

export interface StorageProvider {
  readonly name: 'cloudinary' | 'local';
  put(key: string, data: Buffer, opts: { mimeType: string; isPrivate: boolean; resourceType: ResourceType }): Promise<StoredObject>;
  /** Short-lived URL for private objects. */
  signedUrl(key: string, opts: { resourceType: ResourceType; mimeType: string; expiresInSec: number; fileName?: string }): string;
  /** Poster frame for a stored video, when the provider can generate one. */
  videoThumbnailUrl?(key: string): string | undefined;
  remove(key: string, opts: { resourceType: ResourceType; isPrivate: boolean }): Promise<void>;
}

/** Keys are generated by the server; this guards file paths against traversal. */
export const SAFE_KEY = /^[a-f0-9]{24}\/[a-z]+\/[a-zA-Z0-9-]+(\.[a-z0-9]{2,5})?$/;

function apiBaseUrl(): string {
  return (env.PUBLIC_API_URL ?? `http://localhost:${env.PORT}`).replace(/\/$/, '');
}

export function signLocal(key: string, exp: number): string {
  return createHmac('sha256', env.JWT_REFRESH_SECRET).update(`file:${key}:${exp}`).digest('base64url');
}

export function verifyLocalSignature(key: string, exp: number, sig: string): boolean {
  return Number.isFinite(exp) && exp * 1000 > Date.now() && safeEqual(signLocal(key, exp), sig);
}

/**
 * Local-disk driver for development and single-server installs with a
 * persistent volume. Public media gets an unguessable stable URL; private
 * documents are only reachable through HMAC-signed, expiring URLs.
 */
export class LocalStorage implements StorageProvider {
  readonly name = 'local' as const;
  constructor(private readonly root = path.resolve(env.UPLOAD_DIR)) {}

  private file(key: string, isPrivate: boolean): string {
    if (!SAFE_KEY.test(key)) throw new Error('Unsafe storage key');
    return path.join(this.root, isPrivate ? 'private' : 'public', ...key.split('/'));
  }

  async put(key: string, data: Buffer, opts: { isPrivate: boolean }): Promise<StoredObject> {
    const file = this.file(key, opts.isPrivate);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
    return { key, url: opts.isPrivate ? undefined : `${apiBaseUrl()}/api/files/public/${key}` };
  }

  signedUrl(key: string, opts: { expiresInSec: number; fileName?: string }): string {
    const exp = Math.floor(Date.now() / 1000) + opts.expiresInSec;
    const name = opts.fileName ? `&name=${encodeURIComponent(opts.fileName)}` : '';
    return `${apiBaseUrl()}/api/files/private/${key}?exp=${exp}&sig=${signLocal(key, exp)}${name}`;
  }

  read(key: string, isPrivate: boolean): Promise<Buffer> {
    return readFile(this.file(key, isPrivate));
  }

  async remove(key: string, opts: { isPrivate: boolean }): Promise<void> {
    await unlink(this.file(key, opts.isPrivate)).catch(() => undefined);
  }
}

/** Cloudinary driver. Private documents use `authenticated` delivery + expiring download URLs. */
export class CloudinaryStorage implements StorageProvider {
  readonly name = 'cloudinary' as const;
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  private readonly cld = (require('cloudinary') as typeof import('cloudinary')).v2;

  constructor() {
    this.cld.config({
      cloud_name: env.CLOUDINARY_CLOUD_NAME,
      api_key: env.CLOUDINARY_API_KEY,
      api_secret: env.CLOUDINARY_API_SECRET,
      secure: true,
    });
  }

  private publicId(key: string, resourceType: ResourceType) {
    // Cloudinary keeps the extension in public_id only for raw files.
    return resourceType === 'raw' ? `recrm/${key}` : `recrm/${key.replace(/\.[a-z0-9]+$/, '')}`;
  }

  put(key: string, data: Buffer, opts: { isPrivate: boolean; resourceType: ResourceType }): Promise<StoredObject> {
    return new Promise((resolve, reject) => {
      const stream = this.cld.uploader.upload_stream(
        {
          public_id: this.publicId(key, opts.resourceType),
          resource_type: opts.resourceType,
          type: opts.isPrivate ? 'authenticated' : 'upload',
          overwrite: false,
        },
        (err, res) => (err || !res ? reject(err ?? new Error('Upload failed')) : resolve({ key, url: opts.isPrivate ? undefined : res.secure_url })),
      );
      stream.end(data);
    });
  }

  signedUrl(key: string, opts: { resourceType: ResourceType; expiresInSec: number }): string {
    const ext = key.split('.').pop() ?? '';
    return this.cld.utils.private_download_url(this.publicId(key, opts.resourceType), opts.resourceType === 'raw' ? '' : ext, {
      resource_type: opts.resourceType,
      type: 'authenticated',
      expires_at: Math.floor(Date.now() / 1000) + opts.expiresInSec,
    });
  }

  videoThumbnailUrl(key: string): string {
    return this.cld.url(this.publicId(key, 'video'), { resource_type: 'video', format: 'jpg', transformation: [{ start_offset: 0, width: 480, crop: 'limit' }] });
  }

  async remove(key: string, opts: { resourceType: ResourceType; isPrivate: boolean }): Promise<void> {
    await this.cld.uploader.destroy(this.publicId(key, opts.resourceType), {
      resource_type: opts.resourceType,
      type: opts.isPrivate ? 'authenticated' : 'upload',
      invalidate: true,
    });
  }
}

let provider: StorageProvider | undefined;

export function storage(): StorageProvider {
  if (provider) return provider;
  const cloudinaryConfigured = !!(env.CLOUDINARY_CLOUD_NAME && env.CLOUDINARY_API_KEY && env.CLOUDINARY_API_SECRET);
  const driver = env.STORAGE_DRIVER ?? (cloudinaryConfigured ? 'cloudinary' : 'local');
  provider = driver === 'cloudinary' ? new CloudinaryStorage() : new LocalStorage();
  return provider;
}
