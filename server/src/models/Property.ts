import { Schema, model, type Types } from 'mongoose';
import {
  CONSTRUCTION_STATUSES,
  DEVELOPMENT_STATUSES,
  FACING_DIRECTIONS,
  FURNISHING_STATUSES,
  POSSESSION_STATUSES,
  type ConstructionStatus,
  type DevelopmentStatus,
  type FacingDirection,
  type FurnishingStatus,
  type PossessionStatus,
  LISTING_PURPOSES,
  VERIFICATION_STATUSES,
  type VerificationStatus,
  PROPERTY_STATUSES,
  PROPERTY_TYPES,
  SIZE_UNITS,
  type ListingPurpose,
  type PropertyStatus,
  type PropertyType,
  type SizeUnit,
} from '@recrm/shared';
import { branchField, branchIndexes, tenantFields, tenantGuardPlugin } from './plugins/tenant';
import { syncFields, syncIndexes, type SyncDoc } from './plugins/sync';

export interface PropertyVerification {
  status: VerificationStatus;
  assignedTo?: Types.ObjectId | null;
  submittedBy?: Types.ObjectId | null;
  submittedAt?: Date | null;
  checklist: { key: string; done: boolean; note?: string | null; doneBy?: Types.ObjectId | null; doneAt?: Date | null }[];
  decision?: string | null;
  remarks?: string | null;
  verifiedBy?: Types.ObjectId | null;
  verifiedAt?: Date | null;
  nextVerificationAt?: Date | null;
  history: { status: VerificationStatus; action: string; remarks?: string | null; by?: Types.ObjectId; at: Date }[];
}

export interface PropertyDoc extends SyncDoc {
  _id: Types.ObjectId;
  businessId: Types.ObjectId;
  branchId: Types.ObjectId;
  /** Human id, e.g. RE-000125. Generated by the API, unique per business. */
  propertyId: string;
  propertyType: PropertyType;
  listingPurpose: ListingPurpose;
  status: PropertyStatus;
  title?: string;
  area?: string;
  society?: string;
  block?: string;
  phase?: string;
  sector?: string;
  street?: string;
  plotNumber?: string;
  /** House / unit / file number where it differs from the plot number. */
  unitNumber?: string;
  city?: string;
  possessionStatus?: PossessionStatus;
  developmentStatus?: DevelopmentStatus;
  constructionStatus?: ConstructionStatus;
  furnishing?: FurnishingStatus;
  facing?: FacingDirection;
  corner?: boolean;
  mainRoad?: boolean;
  parkFacing?: boolean;
  amenities?: string[];
  /** Listing availability lapses on this date (status becomes EXPIRED unless renewed). */
  availabilityExpiresAt?: Date | null;
  /** Further owners (joint ownership) besides ownerId. */
  coOwnerIds?: Types.ObjectId[];
  /** Agents handling the listing. */
  agentIds?: Types.ObjectId[];
  priceHistory?: { price: number; at: Date; by?: Types.ObjectId; note?: string }[];
  verification?: PropertyVerification;
  /** Shown on the agency website when published. */
  publicListing?: { published: boolean; publishedAt?: Date | null; headline?: string | null; views: number; inquiries: number };
  size: number;
  sizeUnit: SizeUnit;
  sizeSqft: number;
  askingPrice: number;
  expectedFinalPrice?: number;
  minimumPrice?: number;
  negotiable: boolean;
  ownerId?: Types.ObjectId;
  description?: string;
  latitude?: number;
  longitude?: number;
  location?: { type: 'Point'; coordinates: [number, number] };
  googleMapsUrl?: string;
  bedrooms?: number;
  bathrooms?: number;
  floors?: number;
  coverImageUrl?: string;
  coverThumbnailUrl?: string;
  matchCount: number;
  statusChangedAt?: Date;
  /** When someone last confirmed with the owner that the listing is still on offer at this price. */
  lastVerifiedAt?: Date;
  lastVerifiedBy?: Types.ObjectId;
  searchText: string;
  createdBy: Types.ObjectId;
  updatedBy: Types.ObjectId;
  createdAt: Date;
  updatedAt: Date;
}

const schema = new Schema<PropertyDoc>(
  {
    ...tenantFields,
    ...syncFields,
    ...branchField,
    propertyId: { type: String, required: true, immutable: true },
    propertyType: { type: String, enum: PROPERTY_TYPES, required: true },
    listingPurpose: { type: String, enum: LISTING_PURPOSES, default: 'SALE' },
    status: { type: String, enum: PROPERTY_STATUSES, default: 'AVAILABLE' },
    title: { type: String, maxlength: 150 },
    area: { type: String, trim: true, maxlength: 120 },
    society: { type: String, trim: true, maxlength: 120 },
    block: { type: String, trim: true, maxlength: 60 },
    phase: { type: String, trim: true, maxlength: 60 },
    sector: { type: String, trim: true, maxlength: 60 },
    unitNumber: { type: String, trim: true, maxlength: 60 },
    possessionStatus: { type: String, enum: POSSESSION_STATUSES },
    developmentStatus: { type: String, enum: DEVELOPMENT_STATUSES },
    constructionStatus: { type: String, enum: CONSTRUCTION_STATUSES },
    furnishing: { type: String, enum: FURNISHING_STATUSES },
    facing: { type: String, enum: FACING_DIRECTIONS },
    corner: { type: Boolean, default: false },
    mainRoad: { type: Boolean, default: false },
    parkFacing: { type: Boolean, default: false },
    amenities: { type: [String], default: [] },
    availabilityExpiresAt: { type: Date, default: null },
    coOwnerIds: { type: [{ type: Schema.Types.ObjectId, ref: 'PropertyOwner' }], default: [] },
    agentIds: { type: [{ type: Schema.Types.ObjectId, ref: 'User' }], default: [] },
    priceHistory: {
      type: [{ _id: false, price: Number, at: Date, by: { type: Schema.Types.ObjectId, ref: 'User' }, note: String }],
      default: [],
    },
    publicListing: {
      published: { type: Boolean, default: false },
      publishedAt: { type: Date, default: null },
      headline: { type: String, trim: true, maxlength: 120, default: null },
      views: { type: Number, default: 0 },
      inquiries: { type: Number, default: 0 },
    },
    verification: {
      status: { type: String, enum: VERIFICATION_STATUSES, default: 'NOT_SUBMITTED' },
      assignedTo: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      submittedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      submittedAt: { type: Date, default: null },
      checklist: {
        type: [{ _id: false, key: String, done: Boolean, note: String, doneBy: { type: Schema.Types.ObjectId, ref: 'User' }, doneAt: Date }],
        default: [],
      },
      decision: { type: String, default: null },
      remarks: { type: String, maxlength: 1000, default: null },
      verifiedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      verifiedAt: { type: Date, default: null },
      nextVerificationAt: { type: Date, default: null },
      history: {
        type: [{ _id: false, status: String, action: String, remarks: String, by: { type: Schema.Types.ObjectId, ref: 'User' }, at: Date }],
        default: [],
      },
    },
    street: { type: String, trim: true, maxlength: 120 },
    plotNumber: { type: String, trim: true, maxlength: 60 },
    city: { type: String, trim: true, maxlength: 80 },
    size: { type: Number, required: true, min: 0 },
    sizeUnit: { type: String, enum: SIZE_UNITS, required: true },
    sizeSqft: { type: Number, required: true, min: 0 },
    askingPrice: { type: Number, required: true, min: 0 },
    expectedFinalPrice: { type: Number, min: 0 },
    minimumPrice: { type: Number, min: 0 },
    negotiable: { type: Boolean, default: true },
    ownerId: { type: Schema.Types.ObjectId, ref: 'PropertyOwner' },
    description: { type: String, maxlength: 5000 },
    latitude: Number,
    longitude: Number,
    location: {
      type: { type: String, enum: ['Point'] },
      coordinates: { type: [Number], default: undefined },
    },
    googleMapsUrl: String,
    bedrooms: { type: Number, min: 0 },
    bathrooms: { type: Number, min: 0 },
    floors: { type: Number, min: 0 },
    coverImageUrl: String,
    coverThumbnailUrl: String,
    matchCount: { type: Number, default: 0 },
    statusChangedAt: Date,
    lastVerifiedAt: Date,
    lastVerifiedBy: { type: Schema.Types.ObjectId, ref: 'User' },
    searchText: { type: String, default: '' },
  },
  { timestamps: true, versionKey: false },
);

syncIndexes(schema);
branchIndexes(schema);
schema.index({ businessId: 1, propertyId: 1 }, { unique: true });
schema.index({ businessId: 1, deletedAt: 1, updatedAt: -1 });
schema.index({ businessId: 1, status: 1, listingPurpose: 1, propertyType: 1, askingPrice: 1 });
schema.index({ businessId: 1, society: 1, block: 1 });
schema.index({ businessId: 1, plotNumber: 1 });
schema.index({ businessId: 1, status: 1, availabilityExpiresAt: 1 });
schema.index({ businessId: 1, agentIds: 1 });
schema.index({ businessId: 1, 'verification.status': 1, 'verification.submittedAt': 1 });
schema.index({ businessId: 1, 'verification.nextVerificationAt': 1 });
schema.index({ businessId: 1, ownerId: 1 });
schema.index({ businessId: 1, status: 1, lastVerifiedAt: 1 });
schema.index({ businessId: 1, searchText: 1 });
schema.index({ location: '2dsphere' }, { sparse: true });
schema.index({ businessId: 1, 'publicListing.published': 1, status: 1, deletedAt: 1 });
schema.plugin(tenantGuardPlugin);

export const Property = model<PropertyDoc>('Property', schema, 'properties');
